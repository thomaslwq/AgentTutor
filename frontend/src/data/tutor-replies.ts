export function getTutorReply(question: string, tutorId: string): string {
  const lower = question.toLowerCase()
  const rules = TUTOR_REPLY_RULES[tutorId] ?? TUTOR_REPLY_RULES['chen-mo']
  for (const rule of rules) {
    if (rule.keywords.some((kw) => lower.includes(kw.toLowerCase()))) {
      return rule.reply
    }
  }
  return TUTOR_FALLBACK_REPLIES[tutorId] ?? TUTOR_FALLBACK_REPLIES['chen-mo']
}
